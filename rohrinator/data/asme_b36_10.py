# Main lookup dictionary combining OD and wall thickness
ASME_B36_10_PIPES = {
    nps: {
        "od": od,
        "wall_thickness": WALL_THICKNESS.get(nps, {}),
    }
    for nps, od in PIPE_OD.items()
}


def get_pipe_dimensions(nps: str, schedule: str = "STD") -> dict:
    """
    Get pipe dimensions for a given NPS and schedule.

    Args:
        nps: Nominal pipe size as string (e.g., "2", "1/2", "1-1/4")
        schedule: Pipe schedule (e.g., "STD", "40", "80", "XS")

    Returns:
        Dictionary with od, wall_thickness, and id (inner diameter) in mm

    Raises:
        ValueError: If NPS or schedule not available
    """
    if nps not in PIPE_OD:
        raise ValueError(f"Invalid NPS: {nps}. Available: {list(PIPE_OD.keys())}")

    if nps not in WALL_THICKNESS or schedule not in WALL_THICKNESS[nps]:
        available = list(WALL_THICKNESS.get(nps, {}).keys())
        raise ValueError(f"Schedule {schedule} not available for NPS {nps}. Available: {available}")

    od = PIPE_OD[nps]
    wall = WALL_THICKNESS[nps][schedule]
    id_ = od - 2 * wall

    return {
        "nps": nps,
        "schedule": schedule,
        "od": od,
        "wall_thickness": wall,
        "id": round(id_, 2),
    }


def get_available_schedules(nps: str) -> list:
    """Get available schedules for a given NPS."""
    if nps not in WALL_THICKNESS:
        return []
    return list(WALL_THICKNESS[nps].keys())
